const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const results = path.resolve('test-results');
fs.mkdirSync(results,{recursive:true});
const data = fs.mkdtempSync(path.join(os.tmpdir(),'clinic-ui-'));
const exported = path.join(data,'export.clinic-backup');
const env = {...process.env,CLINIC_TEST_DATA:data};delete env.ELECTRON_RUN_AS_NODE;
let app;
const errors=[];
async function start(){app=await electron.launch({args:['.'],env,timeout:30000});const page=await app.firstWindow();page.on('pageerror',error=>errors.push(error.message));await page.getByRole('heading',{name:'开新处方',exact:true}).waitFor();return page;}
async function main(){
 let page=await start();
 await page.getByRole('button',{name:'备份与设置'}).click();
 await page.getByLabel('诊所名称 *',{exact:true}).fill('安心诊所');
 await page.getByLabel('常用医生姓名 *',{exact:true}).fill('测试医生');
 await page.getByRole('button',{name:'保存设置',exact:true}).click();
 await page.getByText('诊所信息已保存',{exact:true}).waitFor();
 await page.getByRole('button',{name:'药品管理'}).click();
 await page.getByRole('button',{name:'添加药品'}).click();
 await page.getByLabel('药品名称 *',{exact:true}).fill('未保存药品');
 await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:0,checkboxChecked:false});});
 await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click();
 assert.equal(await page.getByLabel('药品名称 *',{exact:true}).inputValue(),'未保存药品');
 await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:1,checkboxChecked:false});});
 await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 await page.getByRole('button',{name:'添加药品'}).click();
 await page.getByLabel('药品名称 *',{exact:true}).fill('测试药品');
 await page.getByLabel('拼音简称',{exact:true}).fill('CSYP');
 await page.getByLabel('规格 *',{exact:true}).fill('10片 / 盒');
 await page.getByLabel('售价（元） *',{exact:true}).fill('12.30');
 await page.getByRole('button',{name:'保存药品',exact:true}).click();
 await page.getByText('药品已保存',{exact:true}).waitFor();
 await page.getByRole('button',{name:'开新处方'}).click();
 await page.getByLabel('患者姓名 *',{exact:true}).fill('测试患者');
 await page.getByLabel('年龄（岁） *',{exact:true}).fill('35');
 await page.getByLabel('诊断 *',{exact:true}).fill('合成测试记录');
 await page.getByLabel('过敏史 *',{exact:true}).fill('不详');
 await page.getByRole('button',{name:'添加到处方'}).click();
 await page.getByLabel('测试药品数量',{exact:true}).fill('2');
 await page.locator('#total').filter({hasText:'¥ 24.60'}).waitFor();
 await page.getByLabel('调整合计',{exact:true}).check();
 await page.getByLabel('调整后的合计金额',{exact:true}).fill('-1');
 await page.getByLabel('调整合计',{exact:true}).uncheck();
 assert.equal(await page.locator('#prescription-form').evaluate(form=>form.checkValidity()),true);
 await page.getByLabel('调整合计',{exact:true}).check();
 await page.getByLabel('调整后的合计金额',{exact:true}).fill('20.00');
 await page.locator('#total').filter({hasText:'¥ 20.00'}).waitFor();
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(results,'prescription.png')});
 // A draft survives a canceled navigation.
 await page.getByRole('button',{name:'月度汇总'}).click();
 await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click();
 assert.equal(await page.getByLabel('患者姓名 *',{exact:true}).inputValue(),'测试患者');
 // Force only the post-commit overview to fail by replacing the backup directory.
 const backupDirectory=path.join(data,'backups');
 fs.renameSync(backupDirectory,backupDirectory+'-parked');fs.writeFileSync(backupDirectory,'fixture');
 await page.keyboard.press('Control+s');
 await page.locator('#notification').filter({hasText:'已保存，但页面信息暂未刷新'}).waitFor();
 assert.equal(await page.getByLabel('患者姓名 *',{exact:true}).inputValue(),'');
 assert.equal(await page.getByRole('button',{name:'保存处方',exact:true}).isVisible(),true);
 fs.unlinkSync(backupDirectory);fs.renameSync(backupDirectory+'-parked',backupDirectory);

 // After save the next patient form starts blank.
 assert.equal(await page.getByLabel('患者姓名 *',{exact:true}).inputValue(),'');
 await page.getByRole('button',{name:'处方记录'}).click();
 await page.getByRole('button',{name:'查看详情',exact:true}).click();
 await page.getByRole('dialog').getByText('合计 ¥ 20.00',{exact:true}).waitFor();
 await page.getByRole('dialog').getByRole('button',{name:'修改',exact:true}).click();
 await page.getByLabel('患者姓名 *',{exact:true}).fill('测试患者更正');
 await page.getByRole('button',{name:'保存处方',exact:true}).click();
 await page.locator('#notification').filter({hasText:'已保存。可以继续填写下一位患者'}).waitFor();
 await page.getByRole('button',{name:'月度汇总'}).click();
 await page.getByText('¥ 20.00',{exact:true}).first().waitFor();
 await page.getByRole('button',{name:'备份与设置'}).click();
 await page.getByRole('button',{name:'立即备份',exact:true}).click();
 await page.getByText('完整备份已保存',{exact:true}).waitFor();
 // Only native file/confirmation dialogs are stubbed; the production IPC/backup implementation runs.
 await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},exported);
 await page.getByRole('button',{name:'导出备份到 U 盘 / 文件夹',exact:true}).click();
 await page.getByText('备份已导出，包含全部处方和照片',{exact:true}).waitFor();assert.ok(fs.statSync(exported).size>0);
 await page.getByRole('button',{name:'处方记录'}).click();
 await page.getByRole('button',{name:'查看详情',exact:true}).click();
 await page.getByRole('button',{name:'作废处方',exact:true}).click();
 await page.getByRole('button',{name:'确认作废',exact:true}).click();
 await page.getByText('处方已作废，记录仍可查询',{exact:true}).waitFor();
 await page.getByRole('button',{name:'备份与设置'}).click();
 await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});dialog.showMessageBox=async()=>({response:1,checkboxChecked:false});},exported);
 await page.getByRole('button',{name:'从备份恢复',exact:true}).click();
 await page.getByText('资料已恢复。恢复前的资料也已单独备份。',{exact:true}).waitFor();
 await page.screenshot({path:path.join(results,'backup-settings.png')});
 await app.close();app=undefined;
 page=await start();
 await page.getByRole('button',{name:'处方记录'}).click();
 await page.getByText('测试患者更正',{exact:true}).waitFor();
 await page.getByRole('button',{name:'查看详情',exact:true}).click();
 await page.getByRole('dialog').getByText('合计 ¥ 20.00',{exact:true}).waitFor();
 await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).click();
 // Minimum supported window size has no horizontal page overflow.
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1000,700));
 await page.getByRole('button',{name:'开新处方'}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.screenshot({path:path.join(results,'minimum-window.png')});
 assert.deepEqual(errors,[]);
 console.log('PASS: setup, medicine, prescription, draft retention, edit, month, backup/export/restore, restart persistence, minimum width; no renderer errors.');
}
main().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(app){try{await app.evaluate(({app})=>app.exit());}catch{}await app.close().catch(()=>{});}fs.rmSync(data,{recursive:true,force:true});});
